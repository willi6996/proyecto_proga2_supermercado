-- Oracle 12c o superior (incluido Oracle Database Free).
-- Ejecutar en un esquema SUPERMERCADO vacio.
-- Los nombres internos se conservan para compatibilidad con el proyecto.
-- No agregar triggers de stock ni de total: los modelos Java los actualizan.
CREATE TABLE cliente (
 id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(150) NOT NULL,
 direccion VARCHAR2(300) NOT NULL,
 telefono VARCHAR2(30) NOT NULL
);
CREATE TABLE mecanico (
 id_mecanico NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(150) NOT NULL,
 especialidad VARCHAR2(100) NOT NULL,
 telefono VARCHAR2(30) NOT NULL
);
CREATE TABLE vehiculo (
 id_vehiculo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente NUMBER NOT NULL REFERENCES cliente(id_cliente),
 placa VARCHAR2(40) NOT NULL UNIQUE,
 marca VARCHAR2(100) NOT NULL,
 modelo VARCHAR2(100) NOT NULL,
 anio NUMBER(4) NOT NULL CHECK (anio >= 1900),
 color VARCHAR2(300) NOT NULL
);
CREATE TABLE repuesto (
 id_repuesto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(150) NOT NULL,
 descripcion VARCHAR2(500) NOT NULL,
 precio NUMBER(12,2) NOT NULL CHECK (precio >= 0),
 existencia NUMBER(10) DEFAULT 0 NOT NULL CHECK (existencia >= 0)
);
CREATE TABLE servicio (
 id_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 descripcion VARCHAR2(500) NOT NULL,
 costo_mano_obra NUMBER(12,2) NOT NULL CHECK (costo_mano_obra >= 0)
);
CREATE TABLE orden (
 id_orden NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_vehiculo NUMBER NOT NULL REFERENCES vehiculo(id_vehiculo),
 id_mecanico NUMBER NOT NULL REFERENCES mecanico(id_mecanico),
 descripcion VARCHAR2(1000) NOT NULL,
 fecha_creacion DATE DEFAULT SYSDATE NOT NULL,
 fecha_final DATE,
 estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL
   CHECK (estado IN ('PENDIENTE', 'EN PROCESO', 'FINALIZADA', 'CANCELADA')),
 total NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (total >= 0)
);
CREATE TABLE abastecimiento (
 id_abastecimiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_repuesto NUMBER NOT NULL REFERENCES repuesto(id_repuesto),
 cantidad NUMBER(10) NOT NULL CHECK (cantidad > 0),
 fecha DATE DEFAULT SYSDATE NOT NULL
);
CREATE TABLE repuesto_utilizado (
 id_repuesto_utilizado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_orden NUMBER NOT NULL REFERENCES orden(id_orden),
 id_repuesto NUMBER NOT NULL REFERENCES repuesto(id_repuesto),
 cantidad NUMBER(10) NOT NULL CHECK (cantidad > 0),
 precio NUMBER(12,2) NOT NULL CHECK (precio >= 0),
 subtotal NUMBER(14,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE TABLE servicio_realizado (
 id_servicio_realizado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_orden NUMBER NOT NULL REFERENCES orden(id_orden),
 id_servicio NUMBER NOT NULL REFERENCES servicio(id_servicio),
 cantidad NUMBER(10) NOT NULL CHECK (cantidad > 0),
 precio NUMBER(12,2) NOT NULL CHECK (precio >= 0),
 subtotal NUMBER(14,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX ix_pedido_cliente ON vehiculo(id_cliente);
CREATE INDEX ix_venta_pedido ON orden(id_vehiculo);
CREATE INDEX ix_venta_empleado ON orden(id_mecanico);
CREATE INDEX ix_abasto_producto ON abastecimiento(id_repuesto);
CREATE INDEX ix_det_venta ON repuesto_utilizado(id_orden);
CREATE INDEX ix_det_producto ON repuesto_utilizado(id_repuesto);
CREATE INDEX ix_srv_venta ON servicio_realizado(id_orden);
CREATE INDEX ix_srv_catalogo ON servicio_realizado(id_servicio);
